P("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
devs = sorted({x[2] for x in avail("noise_behaviour", "2x4")}, key=lambda d: DEV_ORDER.index(d) if d in DEV_ORDER else 99)
