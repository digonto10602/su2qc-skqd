P("Source: `data/results/<lattice>/<family>/noiseless/accuracy.json`.  Bar: $\\max|\\Delta\\psi|<10^{-10}$ and leakage "
  "$<10^{-9}$ (package bar).\n")
P("| lattice | family | done / planned | pass | max $\\lvert\\Delta\\psi\\rvert$ | max leakage | 2q gates (min–max, mean) | 2q depth | qubits | Aer time per circuit (s) |")
