        P(f"| {dev} | {c} | {a['n_2q_native']} | {b['n_2q_native']} | {e(a['f_model'])} | {e(b['f_model'])} | {e(a['acceptance'])} | {e(b['acceptance'])} | "
          f"{e(a['f_hit'])} | {e(b['f_hit'])} | {e(a['r_nc'])} | {e(b['r_nc'])} | {e(a['tv_accepted'])} | {e(b['tv_accepted'])} |")

