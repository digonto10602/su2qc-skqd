def e(x, d=3):
    if x is None:
        return "–"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, int):
        return str(x)
    if x == 0:
        return "0"
    if abs(x) < 1e-3 or abs(x) >= 1e4:
        m, ex = f"{x:.{d - 1}e}".split("e")
        return f"${m}\\times10^{{{int(ex)}}}$"
    return f"{x:.{d}g}"


