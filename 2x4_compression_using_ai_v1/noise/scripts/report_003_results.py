    for sec, r in results.load(lat, fam, dev, t)["rows"].items():
        P(f"| {lat} | `{fam}` | {dev} | {sec} | {r['n_circuits']} | {r['dim_noisy']} | {e(r['dE_noisy'])} | {r['dim_ideal_samples']} | {e(r['dE_ideal_samples'])} |")

