def e(x, d=2):
    """Scientific notation in LaTeX for small energies."""
    if x is None:
        return "--"
    if x == 0:
        return "$0$"
    m, ex = f"{x:.{d}e}".split("e")
    return f"${m}\\times10^{{{int(ex)}}}$"


def g(x, d=3):
    if x is None:
        return "--"
    if isinstance(x, bool):
        return "yes" if x else "**no**"
    if isinstance(x, int):
        return str(x)
    return f"{x:.{d}f}"


def ok(x):
    return "--" if x is None else ("P" if x else "**F**")


def cvs(d):
    return " ".join(ok(d.get(k)) for k in ("CV1", "CV2", "CV3", "CV4", "CV5"))


def chunk_stats(lat, fam, dev):
    files = glob.glob(os.path.join(results.lattice_results(lat), fam, dev, "skqd_samples", "*", "c*.json"))
    shots = sim = tot = 0.0
    commits = set()
    for f in files:
        m = json.load(open(f))
        shots += m["shots"]
        sim += m["timing_s"]["simulate"]
        tot += m["timing_s"]["total"]
        commits.add(m["provenance"]["git_commit"])
    return {"chunks": len(files), "shots": int(shots), "thread_h": tot / 3600.0, "sim_s_per_shot": sim / max(shots, 1),
            "commits": sorted(commits)}


