"""Generate reports/001-quantinuum-device-info.md from data/device_specs_quantinuum.json (no number typed by hand)."""
import json
import os
import subprocess

NOISE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = json.load(open(os.path.join(NOISE, "data", "device_specs_quantinuum.json")))
S = J["sources"]
D = J["devices"]


def fmt(x):
    if isinstance(x, float):
        return f"{x:.2g}" if x < 1e-2 else f"{x:g}"
    return str(x)


def val(dev, key):
    e = D[dev].get(key)
    if e is None:
        return "not published", ""
    v = e["value"]
    s = fmt(v) if not isinstance(v, (dict, list)) else json.dumps(v)
    if "uncertainty" in e:
        s += f" $\\pm$ {fmt(e['uncertainty'])}"
    if e.get("unit"):
        s += f" {e['unit']}"
    src = e.get("source")
    return (s if v is not None else "not published"), (f"[{src}]({S[src]['url']})" if src else "")


commit = subprocess.check_output(["git", "-C", NOISE, "rev-parse", "--short", "HEAD"], text=True).strip()
L = []
L.append("# 001 — Quantinuum device information from public sources (C6)\n")
L.append(f"- Date: {J['access_date']}.  Git commit at generation: `{commit}`.  Prompt in force: owner decision C6 "
         "(`notes/008-owner-decisions-C1-C6.md`, signed 2026-10-21).")
L.append("- Generated by `noise/scripts/report_001_quantinuum.py` from `noise/data/device_specs_quantinuum.json`; "
         "every number below is read from that file.  Related: `reports/002-noise-models.md`.")
L.append("- No Quantinuum account, API, Nexus call or submission was used.  Only public web pages and papers.\n")
L.append("## 1. What was asked\n")
L.append("Find the current public numbers for Quantinuum H2-2 (and H2-1) and Helios-1: gate and SPAM errors, "
         "memory/idle and transport errors, T1/T2, gate durations and parallelism, qubit counts, the HQC cost formula "
         "and the emulator's noise model.  Record each value with its URL, access date, source date and qualification.\n")
L.append("## 2. Actions taken\n")
L.append("I downloaded the H2 and Helios product data sheets (PDF), the Performance Validation page (machine-specific "
         "randomized-benchmarking numbers), the emulator noise-model pages, the operation pages and the costing page "
         "from docs.quantinuum.com, and the Helios (arXiv:2511.05465) and H2 (arXiv:2305.03828) papers from arXiv. "
         "Randomized benchmarking (RB) means: run random sequences of gates of growing length and fit the decay of the "
         "success probability; the decay rate per gate is the *average gate infidelity* (one minus the average "
         "fidelity).  SPAM means state preparation and measurement error.\n")
L.append("## 3. Results\n")
L.append("### 3.1 Machine-specific numbers (Performance Validation page, latest RB sweep)\n")
keys = [("qubits", "qubits"), ("connectivity", "connectivity"), ("parallel_2q_operations", "parallel 2q operations"),
        ("p1_avg_infidelity", "1q gate error (avg infidelity, incl. leakage)"), ("p1_leakage", "1q leakage per gate"),
        ("p2_avg_infidelity", "2q gate error (avg infidelity, incl. leakage)"), ("p2_leakage", "2q leakage per gate"),
        ("memory_error_depth1", "memory error per qubit per depth-1 layer"),
        ("memory_error_linear_depth1", "memory error, linear part, per depth-1 layer"),
        ("memory_error_quadratic_depth1", "memory error, quadratic parameter, per depth-1 layer"),
        ("measurement_crosstalk", "mid-circuit measurement crosstalk"),
        ("global_measurement_crosstalk", "global mid-circuit measurement crosstalk"),
        ("spam_0", "SPAM, prepare 0 read 1"), ("spam_1", "SPAM, prepare 1 read 0"), ("spam", "SPAM (average)"),
        ("T1", "T1"), ("T2", "T2"), ("depth1_time", "depth-1 time")]
L.append("| quantity | H2-2 | H2-1 | Helios-1 |")
L.append("|---|---|---|---|")
for k, lab in keys:
    row = [lab]
    for dev in ("H2-2", "H2-1", "Helios-1"):
        v, s = val(dev, k)
        row.append(f"{v} {s}".strip() if v != "not published" else "–")
    L.append("| " + " | ".join(row) + " |")
L.append("")
L.append("Qualifications (from the JSON):\n")
for dev in ("H2-2", "Helios-1"):
    for k, e in D[dev].items():
        if isinstance(e, dict) and e.get("qualification") and k in dict(keys):
            L.append(f"- {dev}, {dict(keys)[k]}: {e['qualification']}.")
L.append("")
L.append("### 3.2 Product data sheets (generation-wide 'Typical' and 'Max')\n")
L.append("| quantity | H2 typical | H2 max | Helios typical | Helios max |")
L.append("|---|---|---|---|---|")
for k in ("p1", "p2", "spam", "memory_depth1", "mcmr_crosstalk"):
    L.append(f"| {k} | {fmt(D['H2-2']['typical_product_sheet']['value'][k])} | {fmt(D['H2-2']['max_product_sheet']['value'][k])} "
             f"| {fmt(D['Helios-1']['typical_product_sheet']['value'][k])} | {fmt(D['Helios-1']['max_product_sheet']['value'][k])} |")
L.append(f"\nSources: [{S['ds_h2']['title']}]({S['ds_h2']['url']}) ({S['ds_h2']['source_date']}); "
         f"[{S['ds_helios']['title']}]({S['ds_helios']['url']}) ({S['ds_helios']['source_date']}).  'Typical' is the most "
         "representative value during operation, averaged over the gate zones; 'Max' is an upper bound the vendor says "
         "is unlikely to be exceeded.\n")
L.append("### 3.3 Durations, parallelism, gate set, cost\n")
for dev, k in (("H2-2", "native_gates"), ("Helios-1", "native_gates"), ("H2-2", "gate_durations"),
               ("Helios-1", "gate_durations"), ("Helios-1", "parallel_2q_operations"), ("H2-2", "rzz_angle_dependence_paper"),
               ("H2-2", "hqc_formula"), ("Helios-1", "hqc_formula")):
    e = D[dev][k]
    L.append(f"- **{dev}, {k}:** {e['value'] if e['value'] is not None else 'not published'}"
             + (f" — {e['qualification']}" if e.get('qualification') else "") + f" ([{e['source']}]({S[e['source']]['url']})).")
L.append("\nThe HQC formula in LaTeX: $$\\mathrm{HQC}=5+\\frac{C}{5000}\\left(N_{1q}+10\\,N_{2q}+5\\,N_{m}\\right),$$ "
         "with $C$ the number of shots, $N_{1q}$ the PhasedX count, $N_{2q}$ the ZZ/RZZ count and $N_m$ the number of "
         "measurements, resets and initialisations.\n")
L.append("### 3.4 The emulator's noise model (vendor description)\n")
for s in J["emulator_noise_model_description"]["summary"]:
    L.append(f"- {s}")
L.append(f"\nSource: [{S['emu_noise']['title']}]({S['emu_noise']['url']}).  Default parameters (not hardware measurements):\n")
L.append("| parameter | H2-1E | H2-2E | Helios-1E |")
L.append("|---|---|---|---|")
e1 = D["H2-1"]["emulator_H2-1E"]["value"]; e2 = D["H2-2"]["emulator_H2-2E"]["value"]; e3 = D["Helios-1"]["emulator_Helios-1E"]["value"]
for k in e3:
    L.append(f"| {k} | {fmt(e1.get(k, '–'))} | {fmt(e2.get(k, '–'))} | {fmt(e3[k])} |")
L.append(f"\nEmulator dates: {S['emu_h2']['source_date']}; {S['emu_helios']['source_date']}.\n")
L.append("## 4. What the result means\n")
L.append("- The machine-specific H2-2 numbers used by the package and by reviewer-opus "
         f"(2q {fmt(D['H2-2']['p2_avg_infidelity']['value'])}, 1q {fmt(D['H2-2']['p1_avg_infidelity']['value'])}, "
         f"SPAM {fmt(D['H2-2']['spam_0']['value'])} / {fmt(D['H2-2']['spam_1']['value'])}) are the ones currently on the public Performance Validation page; "
         "the reviewer's $f$ for H2-2 therefore rests on public data.")
L.append("- Helios-1 has a lower 2q error than H2-2 but a larger published memory error per depth-1 layer (linear plus "
         "quadratic parts), measured with 98 qubits; how much of that a 20- or 28-qubit circuit pays is not published.")
L.append("- Neither system publishes T1, T2 or per-gate durations; idling is published as a memory error per depth-1 "
         "layer instead (a depth-1 layer = re-pair all qubits and apply 1q and 2q gates to all of them).  The noise "
         "model in report 002 therefore charges memory per depth-1-equivalent layer, not per second.\n")
L.append("## 5. Problems and assumptions\n")
L.append("- The Performance Validation page gives no date for its RB sweep (copyright 2025); the Helios data sheet is "
         "dated 2026-06-09 and the H2 sheet 2025-09-17.")
L.append("- The H2 emulator page heads the H2-2E table 'H2-1E emulators from 2025-07-16' (a vendor typo or copy); recorded as found.")
L.append("- The RZZ angle dependence is published only for the emulator (and in the 2023 H2 paper for the machine at launch); "
         "the model uses the emulator's form.")
L.append("- Helios standard SPAM reads leaked ions as 1, so its |1> SPAM under-counts; the ternary measurement has a larger error.")
open(os.path.join(NOISE, "reports", "001-quantinuum-device-info.md"), "w").write("\n".join(L) + "\n")
print("written")
