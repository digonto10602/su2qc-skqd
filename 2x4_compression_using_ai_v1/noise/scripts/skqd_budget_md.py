"""notes/campaign_budget.md from notes/campaign_budget.json and data/checks/skqd_timing.json (no number typed by hand).

Usage: python scripts/skqd_budget_md.py
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NOISE = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(NOISE, "src"))
import campaign as C  # noqa: E402


def f(x, d=3):
    return "--" if x is None else (f"{x:.{d}g}" if isinstance(x, float) else str(x))


def main():
    B = json.load(open(C.BUDGET_JSON))
    T = json.load(open(os.path.join(NOISE, "data", "checks", "skqd_timing.json")))
    eff = B["ht_efficiency_10_threads_ASSUMED"]
    L = ["# Noisy SKQD campaign: timing and shot budget", "",
         f"Generated by `scripts/skqd_budget_md.py` from `notes/campaign_budget.json` (written by `scripts/skqd_budget.py "
         f"--write`, commit {B['provenance']['git_commit']}, {B['provenance']['created_utc']}) and "
         f"`data/checks/skqd_timing.json` (`scripts/skqd_timing.py`, commit {T['provenance']['git_commit']}).  "
         "No number in this file is typed by hand.", "",
         "## 1. What was asked", "",
         "Owner, 2026-10-29: noisy SKQD sampling with the compressed circuits on all lattices (2x2, 2x3, 2x4), the frozen "
         "2x2 / 2x3 circuits for comparison, primary device model `quantinuum_h2_2`, secondary `quantinuum_helios_1`; "
         "measure the seconds per noisy trajectory first, then fix a shot budget whose total wall time is at most about "
         "24 h on 10 threads, and state exactly what was cut.", "",
         "## 2. Timing (measured)", "",
         f"One *trajectory* = one simulated shot: a random set of Pauli faults is drawn from the device model, the faulty "
         f"circuit is run on the package's exact sparse simulator (`skqd.sparse_sim` through `noise/src/traj_sparse.py`) and "
         f"one bit string is drawn from the final state, then passed through the readout flips.  Probes: "
         f"{T['workers_parallel']} probes in parallel, one BLAS thread each, pinned to CPUs 5-9 (`taskset -c 5-9 nice -n 10`), "
         f"each probe stopped after {T['limits_s']} s per lattice; wall {T['wall_s']:.0f} s.", "",
         "| lattice | family | device | probes | circuits probed | s / trajectory mean | min | max | $f_\\mathrm{gate}$ | fault-free fraction |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    g = collections.defaultdict(list)
    for r in T["rows"]:
        g[(r["lattice"], r["family"], r["device"])].append(r)
    for (lat, fam, dev), v in g.items():
        ps = [x["per_shot_s"] for x in v]
        L.append(f"| {lat} | {C.short(fam)} | {dev} | {len(v)} ({sum(x['shots'] for x in v)} shots) | "
                 f"{', '.join(x['circuit'] for x in v)} | {sum(ps) / len(ps):.4f} | {min(ps):.4f} | {max(ps):.4f} | "
                 f"{v[0]['f_gate']:.3f} | {sum(x['fault_free_fraction'] * x['shots'] for x in v) / sum(x['shots'] for x in v):.3f} |")
    L += ["", "$f_\\mathrm{gate}$ = probability that a trajectory has no gate, memory or idle fault (the model's product of "
          "fault-free probabilities, `traj_sparse.ir_events`); the fault-free fraction is the sampled one.  A fault-free "
          "trajectory costs almost nothing (the clean state is cached), so the cost per shot grows as $f_\\mathrm{gate}$ falls.",
          "", "## 3. Budget rule", "",
          "1. **Plan of record at $f = 1$ (noiseless)**: per-circuit shots $N_c$ and the CV3 equal-shots count $N_\\mathrm{eq}$ "
          "per sector (the D3'-R rule of `scripts/h0_support_plan.d3r_plan` at $y_c = 1$ plus the CV re-size of the CV gates):",
          ""]
    L += ["| lattice | sector | circuits ($k \\le 4$) | $\\sum_c N_c$ | $N_\\mathrm{eq}$ | CV re-size | $\\sum_c N_c$ before re-size | source |",
          "|---|---|---|---|---|---|---|---|"]
    for lat, secs in B["plans_of_record"].items():
        for sec, r in secs.items():
            L.append(f"| {lat} | {sec} | {len(r['plan'])} | {sum(r['plan'].values())} | {r['N_eq']} | x{r['resize']} | "
                     f"{sum(r['plan_1x'].values())} | {r['source']} |")
    L += ["", "2. **Noisy plan**: $N_c' = \\lceil N_c / f_c \\rceil_{100}$ with $f_c = f_\\mathrm{gate}(c)\\,(1-\\bar\\epsilon_\\mathrm{ro})^n$, "
          "the model's clean-shot fraction of circuit $c$ on the device (a clean shot is one with no fault anywhere, readout "
          "included; $\\bar\\epsilon_\\mathrm{ro}$ is the mean readout flip probability, $n$ the qubit count); "
          "$N_\\mathrm{eq}' = \\lceil N_\\mathrm{eq} / \\bar f \\rceil_{100}$ with $\\bar f$ the sector mean of $f_c$.  "
          "$\\lceil x \\rceil_{100}$ = $x$ rounded up to a multiple of 100.  This keeps the expected number of *clean* shots "
          "per circuit equal to the noiseless plan, which is what D3'-R sizes.",
          "3. **Sampled shots**: $\\max(N_c', N_\\mathrm{eq}')$ for $k \\le 4$ and $N_\\mathrm{eq}'$ for $k = 5$; the plan point is "
          "the first $N_c'$ shots of each sequence, CV1/CV2/CV4 read the prefixes $\\varphi N_c'$, $\\varphi = 1/16, \\dots, 1$, "
          "CV3 the first $N_\\mathrm{eq}'$.",
          f"4. **Cost** = sampled shots x (mean measured s / trajectory x {B['timing_margin']}) + {B['startup_s_per_chunk']:.0f} s per "
          f"chunk; chunks of at most {B['chunk_target_s']:.0f} s (half of the 30-minute cap).",
          f"5. **Wall time at 10 threads** = thread-hours / (10 x {eff}).  The factor {eff} is an **assumption, not a "
          "measurement**: the laptop has 6 physical cores with 2 hardware threads each (CPUs k and k+6 share a core), so 10 "
          "busy threads put two on 4 of the 6 cores; I assumed each of those runs at 0.6 of a lone thread, "
          "$(4\\cdot 2\\cdot 0.6 + 2)/10 = 0.68$.  At 5 threads (CPUs 5-9) the probes measured the rate directly.", "",
          "## 4. Cuts (what the full plan would cost, and what was cut)", ""]
    ut = B["uncut_total_thread_hours"]
    L += [f"The uncut plan of record (every family on both devices, the 2x4 B=1 CV re-size x12 included) costs "
          f"{ut:.1f} thread-hours, {ut / (10 * eff):.0f} h of wall time at 10 threads:", "",
          "| lattice | family | device | $\\bar f$ B=0 / B=1 | uncut sampled shots | uncut thread-h |", "|---|---|---|---|---|---|"]
    L += [f"| {x['lattice']} | {x['family']} | {x['device']} | {x['f_mean_B0']:.3f} / {x['f_mean_B1']:.3f} | {x['shots']} | {x['thread_hours']:.1f} |" for x in B["uncut"]]
    L += ["", "Cuts:", ""]
    for k, v in B["cuts"].items():
        L.append(f"- `{k}`: {v}")
    for s in B["skipped"]:
        L.append(f"- skipped: {s['lattice']} {s['family']} on {s['device']} -- {s['reason']}")
    L += ["", "What the cuts mean:", "",
          "- **2x4 B=1 at the 1x D3'-R plan** (the plan before the CV re-size): the D3'-R guarantee is kept (with clean shots "
          "alone, recall of $S_{99.9}$ at least 0.9 with probability at least 0.95, `validation/CV_2x4_plan.json` "
          "`P_recall_S999_ge_target`), but in the noiseless emulation CV1/CV2 at B=1 needed the x12 re-size, so CV1/CV2 at "
          "2x4 B=1 are expected to fail at this size for reasons of shots, not of noise; the ideal samples of the same size "
          "are the control for that.",
          "- **Helios 2x4 classB_v2 at half the f-scaled shots**: the clean-count guarantee holds at half strength "
          "($\\lambda^*/2$ expected clean counts per $S_{99}$ state).",
          "- **Skipped cells** keep the existing short noise runs (`noise_behaviour`) and the analytic clean fraction "
          "(`analytic_f`) of reports/003.", "",
          "## 5. The budget", "",
          "| prio | lattice | family | device | s / shot (x margin) | $\\bar f$ B=0 / B=1 | sampled shots B=0 | sampled shots B=1 | "
          "$N_\\mathrm{eq}'$ B=0 / B=1 | chunks | thread-h | cumulative thread-h | cut |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in B["table"]:
        L.append(f"| {r['priority']} | {r['lattice']} | {r['family']} | {r['device']} | {r['s_per_shot']:.4f} | "
                 f"{r['f_mean_B0']:.3f} / {r['f_mean_B1']:.3f} | {r['shots_B0']} | {r['shots_B1']} | "
                 f"{r['N_eq_B0']} / {r['N_eq_B1']} | {r['chunks']} | {r['thread_hours']:.1f} | "
                 f"{r['cumulative_thread_hours']:.1f} | {r['cuts'] or ''} |")
    tot = B["total_thread_hours"]
    core = sum(r["thread_hours"] for r in B["table"] if not r["family"].endswith("_v1"))
    L += ["", f"Total {tot:.1f} thread-hours ({len(B['jobs'])} chunk jobs).  Without the optional v1 tail: {core:.1f} "
          f"thread-hours = {core / (10 * eff):.1f} h at 10 threads (assumed efficiency) or {core / 5:.1f} h at 5 threads.  "
          f"With the v1 tail: {tot / (10 * eff):.1f} h / {tot / 5:.1f} h.", "",
          "## 6. Run", "",
          "`nohup nice -n 10 python scripts/skqd_queue.py >> logs/skqd_queue.log 2>&1 &`; the worker count and CPU set are "
          "read from `logs/skqd_queue.ctl` before every dispatch (`{\"workers\": 5, \"cpus\": \"5-9\"}` now; "
          "`{\"workers\": 10, \"cpus\": \"0-9\"}` when the owner allows 10 threads; never more than 10).  Analysis per cell: "
          "`python scripts/skqd_analyse.py <lattice> <family> <device>`; aggregate: `python scripts/skqd_aggregate.py`.", ""]
    out = os.path.join(NOISE, "notes", "campaign_budget.md")
    with open(out, "w") as fh:
        fh.write("\n".join(L))
    print("wrote", out)


if __name__ == "__main__":
    main()
