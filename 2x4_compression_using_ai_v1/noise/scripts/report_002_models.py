         "*process infidelity*: $$p_{\\rm fault}=r\\,\\frac{d+1}{d},\\qquad p_{\\rm fault,1q}=\\tfrac32 r_{1q},\\quad "
         "p_{\\rm fault,2q}=\\tfrac54 r_{2q},$$ with $d=2^{n_q}$, each of the $d^2-1$ non-identity Paulis with probability "
         "$p_{\\rm fault}/(d^2-1)$, applied right after every native gate.  (The package's `device_req.clean_shot_fraction` "
