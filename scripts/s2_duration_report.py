    dd_rows = []
    for key in sorted(s):
        r = s[key]
        dd_rows.append([r["family"], r["regime"].split(" ")[0], key.split("|")[2],
                        f"{r['S_T1']['mean']:.3f}", f"{r['S_T2']['mean']:.3f}",
                        f"{r['S_DD']['mean']:.3f}",
                        f"{r['f_idle_dd_off']['mean']:.2e}"])

    # sentences whose numbers are derived from the JSON, never typed
