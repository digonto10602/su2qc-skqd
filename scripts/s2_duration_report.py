    pin = v[key_pin] if key_pin else None
    sm_pin = next(s[k] for k in s if k.startswith("exact|pinned|ibm_fez"))
    q_worst = max(h["per_qubit"].items(), key=lambda kv: kv[1]["S_T2"])
