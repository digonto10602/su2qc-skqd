                      f"{r['idle_ratio']['mean']:.3f}", f"{r['S_T1_T2_ratio']['mean']:.3f}",
                      f"{r['f_gates_ratio']['mean']:.3f}",
                      f"{r['f_idle_ratio_fixed_over_exact']['mean']:.3f}",
                      f"{r['yield_ratio']['mean']:.3f}", r["winner"],
