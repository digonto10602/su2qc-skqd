def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=os.path.join("data", "S2_duration_compare.json"))
    ap.add_argument("--md", default=os.path.join("reports", "S2_duration_and_idle_2x2.md"))
    a = ap.parse_args()
    p = a.json if os.path.isabs(a.json) else os.path.join(ROOT, a.json)
    with open(p) as fh:
        d = json.load(fh)
    mp = a.md if os.path.isabs(a.md) else os.path.join(ROOT, a.md)
    os.makedirs(os.path.dirname(mp), exist_ok=True)
    with open(mp, "w") as fh:
        fh.write(report_text(d))
    print(f"wrote {os.path.relpath(mp, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
